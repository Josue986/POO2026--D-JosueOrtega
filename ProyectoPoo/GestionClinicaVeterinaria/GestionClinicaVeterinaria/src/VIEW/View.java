    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        System.out.println("CedulaActual: " + cedulaActual); // ← agregar
        String nombre = jTextField5.getText();
        System.out.println("Nombre: " + nombre); // ← agregar
        double peso = Double.parseDouble(jTextField7.getText());
        String fechadenacimiento = jTextField8.getText(); // ← agrega esta línea

        String nombreEspecie = JOptionPane.showInputDialog("Ingrese la especie:");
        nombreEspecie = nombreEspecie.substring(0, 1).toUpperCase()
                + nombreEspecie.substring(1).toLowerCase();

        Especie e = controllerEsp.buscarPorNombre(nombreEspecie);
        if (e == null) {
            String idEspecie = JOptionPane.showInputDialog("Ingrese el ID de la especie:");
            controllerEsp.agregar(idEspecie, nombreEspecie);
            e = controllerEsp.buscarPorNombre(nombreEspecie);
        }
        String idMascota = jTextField6.getText();

        controllerMas.agregar(idMascota, nombre, fechadenacimiento, peso, e, cedulaActual);
        controllerMas.guardar();
        controllerEsp.guardar();
        actualizarTablaMascota(cedulaActual);
        actualizarTablaEspecies();
        JOptionPane.showMessageDialog(this, "Mascota agregada!");
    }//GEN-LAST:event_jButton4ActionPerformed

