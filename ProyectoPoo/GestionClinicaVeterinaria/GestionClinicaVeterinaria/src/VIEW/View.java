    private void actualizarTablaPatologias() {
    javax.swing.table.DefaultTableModel model
            = (javax.swing.table.DefaultTableModel) jTable10.getModel();
    model.setRowCount(0);

    // Contar frecuencia de cada diagnóstico
    Map<String, Integer> frecuencias = new HashMap<>();
    for (ConsultaMedica c : controllerConsulta.getConsultas()) {
        String diag = c.getDiagnostico();
        if (diag != null && !diag.isEmpty()) {
            frecuencias.put(diag, frecuencias.getOrDefault(diag, 0) + 1);
        }
    }

    // Ordenar por frecuencia descendente
    frecuencias.entrySet().stream()
        .sorted((a, b) -> b.getValue() - a.getValue())
        .forEach(entry -> model.addRow(new Object[]{
            entry.getKey(),
            entry.getValue()
        }));
}

